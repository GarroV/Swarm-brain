import CoreGraphics

// Переливание значка шмеля, пока капсула записи стоит в ПРОСТОЕ — просьба владельца
// 03.09.2026: «пока капсула в простое, можем какую-то анимацию добавить жопке шмеля? типа
// чтоб переливалась желтым/черным».
//
// «Простой» здесь = капсула видна, запись идёт, но звука нет: ни своего микрофона, ни
// системной дорожки. Это единственное состояние, в котором капсула вообще висит и при этом
// ничего не происходит (в покое приложение живёт значком в меню-баре, капсулы нет).
// Смысл анимации ровно в этом: показать, что рекордер жив и слушает, а не завис.
//
// Логика вынесена из RecorderWidget, потому что порог и фаза — то, что легко перепутать
// знаком или переполнением, и то, что дешевле проверить тестом, чем глазами на экране.
public enum IdleShimmer {
    /// Ниже этого уровня считаем, что звука нет (шкала уровней 0…1).
    public static let silenceLevel: CGFloat = 0.02
    /// Столько тиков тишины подряд — и включаем переливание. Тик капсулы = 0.2 с,
    /// 15 тиков = 3 секунды: мгновенно реагировать на паузу в речи не нужно.
    public static let silentTicksToStart = 15

    /// Пора ли переливаться: тихо И тишина держится достаточно долго.
    public static func shouldShimmer(micLevel: CGFloat, systemLevel: CGFloat, silentTicks: Int) -> Bool {
        guard micLevel < silenceLevel, systemLevel < silenceLevel else { return false }
        return silentTicks >= silentTicksToStart
    }

    /// Фаза волны 0…1…0 (треугольник) по номеру кадра. Треугольник, а не пила: цвет обязан
    /// возвращаться назад плавно, иначе на стыке цикла заметен скачок.
    public static func phase(step: Int, frames: Int) -> CGFloat {
        guard frames > 1 else { return 0 }
        let period = frames * 2 - 2                     // вперёд и обратно без повтора краёв
        let i = ((step % period) + period) % period     // отрицательный шаг тоже валиден
        let forward = i < frames ? i : period - i
        return CGFloat(forward) / CGFloat(frames - 1)
    }
}
