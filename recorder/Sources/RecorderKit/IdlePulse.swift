import CoreGraphics

// Когда значок шмеля в капсуле «дышит» — просьба владельца 03.09.2026: «пока капсула в
// простое, можем какую-то анимацию добавить жопке шмеля», уточнение — «давай сделаем
// пульсацию, а не бегающую дорожку. и пульсацию неторопливую».
//
// «Простой» = капсула видна, запись идёт, но звука нет: ни своего микрофона, ни системной
// дорожки. Это единственное состояние, где капсула висит и при этом ничего не происходит
// (в покое приложение живёт значком в меню-баре, капсулы нет). Смысл — показать, что
// рекордер жив и слушает.
//
// Здесь только УСЛОВИЕ. Саму пульсацию рисует Core Animation (opacity, autoreverses):
// первая редакция крутила покадровую перекраску марки, и это читалось как бегущая дорожка,
// а не как дыхание — плюс трогало цвет самой картинки, чего делать нельзя.
public enum IdlePulse {
    /// Ниже этого уровня считаем, что звука нет (шкала уровней 0…1).
    public static let silenceLevel: CGFloat = 0.02
    /// Столько тиков тишины подряд — и начинаем дышать. Тик капсулы = 0.2 с,
    /// 15 тиков = 3 секунды: реагировать на короткую паузу в речи незачем.
    public static let silentTicksToStart = 15
    /// Полупериод дыхания. С `autoreverses` полный цикл — 3.6 с: «пульсацию неторопливую»
    /// (владелец 03.09.2026).
    public static let halfPeriod = 1.8
    /// До какой прозрачности гаснет значок на вдохе. НЕ глубже: первая редакция уводила
    /// значок в 0.45, и он почти пропадал — замер по скриншоту дал 20 светлых пикселей
    /// против 415 в норме, то есть это читалось как исчезновение марки, а не как дыхание.
    public static let minOpacity = 0.62

    /// Пора ли дышать: тихо И тишина держится достаточно долго.
    public static func shouldPulse(micLevel: CGFloat, systemLevel: CGFloat, silentTicks: Int) -> Bool {
        guard micLevel < silenceLevel, systemLevel < silenceLevel else { return false }
        return silentTicks >= silentTicksToStart
    }
}
