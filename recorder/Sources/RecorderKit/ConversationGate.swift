import Foundation

/// «Разговор уже начался?» — собеседников было слышно два тика подряд (≈10 с).
///
/// Правила авто-стопа «звонок смолк» (3 мин тишины обеих дорожек; микрофон свободен 15 с) ловят
/// КОНЕЦ разговора. До его начала они ловят ожидание: человек нажал «Записать» за 5 минут до
/// встречи, сидит в лобби, собеседников ещё нет — и запись обрывалась раньше, чем кто-то
/// заговорил, а сама встреча шла уже без записи (issue #379: 17.09.2026 запись 6,5 мин тишины,
/// остановка ровно через 3 мин после последнего звука). Пока ворота закрыты, эти правила
/// запись не останавливают; «собеседников не слышно 15 мин», закрытая вкладка комнаты, лимиты
/// и сон работают как прежде.
///
/// Один громкий тик ворота не открывает: звук входа в звонок или уведомление — это «блип», а
/// не разговор (та же устойчивость, что у сброса счётчика тишины). Открывшись, ворота до конца
/// записи не закрываются: пауза в живом разговоре — забота правил тишины, а не ворот.
public struct ConversationGate: Equatable {
    public static let ticksToOpen = 2

    public private(set) var isOpen = false
    private var audibleStreak = 0

    public init() {}

    public mutating func observe(otherSideAudible: Bool) {
        guard !isOpen else { return }
        audibleStreak = otherSideAudible ? audibleStreak + 1 : 0
        if audibleStreak >= Self.ticksToOpen { isOpen = true }
    }
}
