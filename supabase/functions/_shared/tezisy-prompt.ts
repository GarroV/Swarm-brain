// потому что читатель уносит неверный факт. Отдельная константа — чтобы тест проверял наличие.
export const NO_INVENTED_LINKS_RULE =
  "НЕ ВЫДУМЫВАЙ СВЯЗИ МЕЖДУ ТЕМАМИ. Соседство реплик в стенограмме НЕ означает, что вопросы " +
  "связаны: в одной встрече люди подряд задают вопросы про совершенно разное. Пиши «в контексте X», " +
  "«в рамках X», «вместе с X», «из-за X» ТОЛЬКО если эта связь прямо сказана в тексте. Иначе — " +
  "разводи такие вопросы по РАЗНЫМ пунктам (а разные темы — по разным разделам), каждый сам по себе.\n" +
  "РАЗНЫЕ НАЗВАНИЯ — РАЗНЫЕ СУЩНОСТИ, пока в тексте не сказано, что это одно и то же (похожее " +
  "звучание — не повод склеивать: Whisper искажает названия).\n" +
  "ЕСЛИ на заданный вопрос в записи ответа НЕТ — так и напиши («ответ в записи не прозвучал» / " +
  "«вопрос остался без ответа»). НЕ достраивай ответ из соседних реплик и не выдавай чужой ответ " +
  "за ответ на этот вопрос. Сам вопрос при этом сохрани — он и есть факт встречи.\n" +
  "РАЗВЕСТИ ≠ ВЫБРОСИТЬ. Осторожность со связями НЕ повод терять факты: тема, которую не к чему " +
  "привязать, получает СВОЙ пункт (или свой раздел) со своими деталями — что спросили, какие " +
  "назвали цифры и сроки, что просили передать команде. Ничего не удаляй только потому, что связь " +
  "неясна или ответа не было. И это правило НЕ отменяет раздел «Решения и договорённости»: то, о " +
  "чём реально договорились, фиксируй там, как и раньше.";

