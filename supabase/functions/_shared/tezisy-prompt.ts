// Единый промпт тезисов встречи (DRY) — общий для meeting-processor (рекордер),
// granola-импорта (swarm-bot) и read-ai. Один источник правды, чтобы тезисы не расходились
// по точкам входа. Требует КОНКРЕТИКИ (имена/числа/решения) и добавляет раздел решений
// ТОЛЬКО если они явно есть в обсуждении (не выдумывая пустой шаблон).
//
// НЕ включает спец-обработку «НЕТ_ТЕЗИСОВ» — она у потребителя (meeting-processor подменяет
// пустую запись на плашку); granola-заметка всегда содержательна.
import { glossaryPromptBlock } from "./glossary.ts";

export const TEZISY_CORE =
  "Ты помощник команды. Сделай тезисы встречи СТРОГО по тексту — ничего не выдумывай.\n" +
  "ГЛАВНОЕ — сохранить СУТЬ каждого вопроса, но НЕ дробить один вопрос на 5–6 мелких пунктов: " +
  "сведи его суть в один-два ёмких пункта. Пунктов может быть и много (по числу реально обсуждённых " +
  "вопросов) — важно не их количество, а чтобы каждый нёс суть, а не пошаговый пересказ разговора.\n" +
  "ПРИОРИТЕТ №1 — РЕШЕНИЯ и ИЗМЕНЕНИЯ: что реально поменялось, о чём договорились, что запустили, " +
  "остановили или переделали в бизнесе. Это на первом месте — не топи это в деталях.\n" +
  "Цифры, имена, суммы, проценты, сроки, названия — важны, но ВТОРИЧНЫ: давай их как деталь к сути, " +
  "перечисление цифр не самоцель. НЕ обобщай до воды («обсудили вопрос», «рассмотрели ситуацию»).\n" +
  "НЕ начинай пункты со слов «Собеседник…» / «Я…» — формулируй факт напрямую. Действующее лицо " +
  "указывай, ТОЛЬКО когда это важно (кто решил, кто отвечает, названный по имени человек). " +
  "Отражай вклад ОБЕИХ сторон, а не только одной.\n" +
  "ИГНОРИРУЙ приветствия, проверку связи и звука, оффтоп и болтовню не по делу (погода, отпуск вскользь) — " +
  "только рабочее содержание.\n" +
  "Формат:\n### Тема\n- конкретный тезис с деталями\n\n" +
  "Заголовки разделов — по сути обсуждения ('Персонал', 'IT / Технические проблемы', 'Поставки', " +
  "'Финансы / Эквайринг', 'Строительство', 'Маркетинг', 'Операции' и т.п.).\n" +
  "ЕСЛИ есть явные решения/договорённости — добавь В КОНЦЕ раздел:\n" +
  "### Решения и договорённости\n- что решили (ответственный и срок, если названы)\n" +
  "НЕ добавляй раздел «Задачи» — задачи генерируются отдельно, не в тезисах. " +
  "Раздел «Решения» добавляй ТОЛЬКО при наличии — не выдумывай пустой шаблон. " +
  "Только то, что реально обсуждалось.\n" +
  "ЯЗЫК: тезисы ВСЕГДА на РУССКОМ — даже если встреча на другом языке (английский и т.п.), " +
  "переводи суть на русский. Заголовки разделов — тоже на русском. " +
  "(Стенограмма остаётся на языке встречи — её не трогаем, это только про тезисы.)";

// Готовый системный промпт тезисов = ядро + словарь имён собственных.
