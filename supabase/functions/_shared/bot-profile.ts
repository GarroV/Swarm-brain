// Профиль бота встреч на сервере (D029, T177): всё, что в поведении бота донастраивается, — здесь,
// в одном месте. Ядро (claim/ingest/processor, пропуски, сторожа) берёт эти значения отсюда и
// больше нигде их не повторяет: переименовать бота, добавить площадку, сдвинуть тайминги двери
// или окно автозапуска — правка этого файла (и `bot/src/orchestrator/profile.ts`), а не ядра.
//
// Протокол доверия (пропуск на встречу, личность агента, сверка заявки) — НЕ настройка и сюда не
// переезжает: он живёт в `agent-auth.ts`, `agent-grant.ts`, `meeting-claim/agent-scope.ts`.
//
// Бот читает свои значения из `bot/src/orchestrator/profile.ts`. Общие поля обязаны совпадать —
// это держит контрактный тест `bot-profile.test.ts`, а не память. Граница ядра — `bot-boundary.test.ts`.
//
// Файл без импортов намеренно: его читают и функции, и тест контракта.

/** Площадки, куда бот умеет войти (адаптер есть только у Google Meet). */
export type BotPlatform = "meet";

export const BOT_PROFILE = {
  /** Имя бота в текстах людям. Подставляется в шаблоны как `{bot}`. */
  name: "scriba",
  /**
   * Площадки с адаптером у бота. Ссылку другой площадки сервер распознаёт (сверка комнаты,
   * текст отказа), но приглашение на неё не заводит — оно кончалось бы пустой встречей.
   */
  platforms: ["meet"] as readonly BotPlatform[],
  /** Дверь: сколько бот ждёт до первого сигнала, пауза до единственного повтора, всего сигналов. */
  door: { waitSeconds: 90, repeatSeconds: 180, maxAttempts: 2 },
  /** Потолок длины встречи бота; после него — досылка частей. */
  maxMeetingMinutes: 240,
  /** Сколько после потолка длины пропуску ещё жить: досылка частей и их обработка. */
  uploadTailMinutes: 120,
  /**
   * Сторож оборванной записи: бот бьёт раз в 2 мин, 10 мин тишины — пять пропущенных ударов,
   * а не сетевой всплеск.
   */
  silentMinutes: 10,
  /**
   * Подсказка-глоссарий Whisper (`prompt`) для записей бота. Выключена (#620): бот пишет
   * смешанный звук звонка, и на тихих и шумных отрезках Whisper с подсказкой галлюцинирует её же
   * словами («Нови Сад, Нови Сад 2…»), а фильтр мусора выбрасывает часть целиком — живой звонок
   * 29.09.2026 дал пустую стенограмму при 7,8 мин речи. Без подсказки тот же файл трижды подряд
   * распознан внятно. Рекордер (чистая дорожка микрофона) подсказку сохраняет.
   */
  whisperGlossaryHint: false,
  /** Автозапуск по календарю: окно «идти ли сейчас» относительно начала события. */
  autojoin: {
    /** Раньше чем за столько до начала бот не выходит. */
    leadMs: 2 * 60_000,
    /** Опоздание больше этого — встреча уже в разгаре, бот не идёт. */
    lateMs: 10 * 60_000,
    /** Колонка согласия человека на автозапуск (`allowed_users`, D021). По умолчанию false. */
    consentColumn: "scriba_autojoin",
  },
} as const;

/**
 * Давать ли Whisper подсказку-глоссарий для выгрузки этого источника. Источник бота —
 * `agent:<id>` (`process_state.source`); для него решает профиль, для людей — всегда да.
 */
export function useGlossaryHint(source: string | undefined): boolean {
  if (source?.startsWith("agent:") === true) return BOT_PROFILE.whisperGlossaryHint;
  return true;
}
