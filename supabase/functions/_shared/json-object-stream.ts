// Инкрементальный разбор потока от модели: выдёргивает каждый JSON-объект верхнего уровня
// в тот момент, когда он ДОПИСАН, не дожидаясь конца ответа.
//
// Зачем: извлечение задач из встречи занимает 3–5 секунд (замер по прод-логам: обычный вызов
// swarm-api 200–600 мс, а этот — 2.9/3.2/5.3 с), и всё это время уходит на генерацию — модель
// пишет семь задач с описаниями по токену. Дождаться конца значит показать пустой экран на
// пять секунд; отдать каждую задачу сразу после её закрывающей скобки — значит показать первую
// примерно через секунду и дать человеку начать вычитку, пока приезжают остальные.
//
// Почему свой сканер, а не «попросить модель отдавать JSON Lines»: промптов извлечения задач в
// проекте уже три (бот, api, дубли), и заводить четвёртый ради формата потока — прямой путь к
// расхождению. Формат ответа остаётся один, разбирать поток умеет код.
//
// Разбор нарочно НЕ является полноценным JSON-парсером: он только считает глубину фигурных
// скобок вне строк. Этого достаточно, чтобы нарезать поток на объекты, а валидность каждого
// куска потом проверит обычный JSON.parse.

export type JsonObjectScanner = {
  /** Скормить очередной кусок потока. Возвращает объекты, дописанные ИМЕННО в этом куске. */
  push(chunk: string): string[];
};

export function createJsonObjectScanner(): JsonObjectScanner {
  // Незакрытый объект копится здесь; всё, что вне объектов (скобки массива, запятые,
  // markdown-обёртка, переводы строк), просто не попадает в буфер.
  let buffer = "";
  let depth = 0;
  let inString = false;
  let escaped = false;

  return {
    push(chunk: string): string[] {
      const done: string[] = [];
      for (const ch of chunk) {
        if (depth > 0) buffer += ch;

        if (escaped) {
          // Предыдущий символ был «\» — этот съедается им целиком, чем бы он ни был.
          escaped = false;
          continue;
        }
        if (ch === "\\") {
          // Экранирование учитываем ТОЛЬКО внутри строки: вне строки «\» в JSON не бывает,
          // а модель может прислать его в markdown-обёртке и сбить состояние.
          if (inString) escaped = true;
          continue;
        }
        if (ch === '"') {
          inString = !inString;
          continue;
        }
        if (inString) continue;

        if (ch === "{") {
          if (depth === 0) buffer = "{"; // начало нового объекта: всё прежнее — мусор между ними
          depth++;
        } else if (ch === "}") {
          if (depth > 0) {
            depth--;
            if (depth === 0) {
              done.push(buffer);
              buffer = "";
            }
          }
        }
      }
      return done;
    },
  };
}
