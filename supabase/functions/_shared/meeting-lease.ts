// Лиз права транскрибации (meetings.lease_expires_at) — единственный источник правды о том,
// сколько времени за держателем claim'а закреплена встреча.
//
// Почему модуль, а не константа в meeting-claim (issue #285): лиз ВЫДАВАЛСЯ в claim, а продлевать
// его было некому — ни ingest, ни процессор его не трогали. Через 30 минут после claim, пока
// транскрипта ещё нет, встреча снова считалась свободной, и право забирал любой следующий
// претендент — в том числе с записью на 3 минуты, потому что ветка «встреча свободна» длительности
// не сравнивает вовсе. Это тот же класс потери, что инцидент 17.08.2026 (3 минуты вместо 2ч26м),
// только через другую дверь. На проде за 60 дней 4 встречи обрабатывались дольше 30 минут — окно
// открывалось регулярно.
//
// Правило теперь: пока обработка ЖИВА (аудио принято, процессор двигает прогресс), лиз
// продлевается вместе с прогрессом. Умерла — лиз истекает, и встречу законно подхватывает
// следующий претендент: иначе запись зависла бы навсегда за пропавшим держателем.
//
// Продлевают: ingest и процессор, пока обработка жива; meeting-heartbeat — ударом бота scriba
// по своей встрече (бот заявляется до захода в звонок и пишет дольше срока, а claim после
// истечения занял бы встречу как брошенную). Один срок на все функции: разойдись они, живой
// держатель выглядел бы истёкшим раньше, чем его продлят. До слияния main в ствол scriba
// 28.09.2026 у стройки был свой дубль этого модуля (_shared/meeting-lease.ts) — сведён сюда.

/** На сколько выдаётся и продлевается право транскрибации. */
export const CLAIM_LEASE_TTL_SEC = 1800;

/** ISO-момент, до которого держится право, считая от `from` (Date или ISO-строка; по умолчанию — сейчас). */
export function claimLeaseUntil(from: Date | string = new Date()): string {
  const fromMs = typeof from === "string" ? Date.parse(from) : from.getTime();
  return new Date(fromMs + CLAIM_LEASE_TTL_SEC * 1000).toISOString();
}

/**
 * Потолок записанных секунд — сутки, один на удар бота (meeting-heartbeat) и на claim. Завышенное
 * значение навсегда закрыло бы встречу от перехвата более полной записью, поэтому явно невозможное
 * отбивается 400, а не пишется. Разойдись потолки, через claim проходило бы то, что heartbeat отбивает.
 */
export const MAX_RECORDED_SECONDS = 86_400;
