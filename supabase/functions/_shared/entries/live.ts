// «Живая запись» (встреча, заметка, документ) — одно определение на весь код (#569).
//
// С 01.10.2026 запись не удаляется, а архивируется (`entries.archived_at`), как задачи с
// 21.09.2026 (#427). Каждый читатель таблицы обязан это знать — у задач забыли ровно читатели,
// написанные мимо общего модуля, и архивная задача продолжала жить в спринтах и напоминаниях.
//
// Поэтому условие живёт здесь, а выборка оборачивается:
// `onlyLiveEntries(supabase.from("entries").select(...))`. Тест-сторож `live.guard.test.ts`
// проходит по всем выборкам из `entries` и валит прогон, если выборка не обёрнута и не помечена
// осознанным исключением `// archive-ok: <почему>`. Он же валит физическое `.delete()` записи
// без такой пометки: удалять запись теперь нельзя, только архивировать (`archive.ts`).
//
// В SQL то же условие — `e.archived_at is null` (поиск, миграция 20261002100000).

/** Колонка архива у `entries`. */
export const ENTRY_ARCHIVED_COLUMN = "archived_at";

/** Минимум от построителя запроса supabase-js, который нужен фильтру. */
interface Filterable<T> {
  is(column: string, value: null): T;
}

/** Оставить в выборке только живые (не архивные) записи. Тип построителя сохраняется. */
export function onlyLiveEntries<T extends Filterable<T>>(query: T): T {
  return query.is(ENTRY_ARCHIVED_COLUMN, null);
}
