/**
 * Сравнение строк за постоянное время — против timing-атак на секреты.
 *
 * Наивное `a === b` выходит из сравнения на первом несовпавшем символе, поэтому время
 * ответа выдаёт длину совпавшего префикса, и секрет можно подобрать посимвольно.
 *
 * ⚠️ Длины сравниваются обычным способом: расхождение длины утечкой не считаем
 * (её и так видно), а маскировать её пришлось бы фиксированным буфером.
 */
export function timingSafeEq(a: string, b: string): boolean {
  if (a.length !== b.length) return false;
  let d = 0;
  for (let i = 0; i < a.length; i++) d |= a.charCodeAt(i) ^ b.charCodeAt(i);
  return d === 0;
}
