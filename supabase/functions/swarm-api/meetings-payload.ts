// Список колонок — единый канон ENTRY_COLUMNS в entries-guard.ts (обязательный слой доступа
// к entries). Здесь только то, что специфично для СПИСОЧНОГО ответа /meetings: урезание.

// Форма ответа GET /meetings. Вынесено отдельно, чтобы решение «какие колонки уезжают
// в браузер» было в одном месте и под тестом, а не растворялось в 2000-строчном роутере.
//
// Зачем вообще: до 26.08.2026 хендлер делал select("*") и отдавал ~10 МБ на 230 встреч,
// из которых 61% — embedding (4.2 МБ) и fts (1.8 МБ), т.е. колонки, которых НЕТ в типе
// Entry (miniapp/src/types.ts) — фронт физически не мог их прочитать. Ещё 2.7 МБ — полные
// транскрипты, которые в списке не рендерятся (issue #102).
//
// ГДЕ РЕЖЕТСЯ (изменено 25.09.2026, issue #490): в SQL, а не здесь. Список берёт готовые
// generated-колонки `content_preview`/`summary_preview`/`list_truncated` через
// ENTRY_LIST_COLUMNS. Прежняя схема — выбрать полный текст и обрезать в JS — стоила 654 мс
// базы на 283 встречах против 15 мс сейчас: время уходило на чтение TOAST и сериализацию
// текста, который тут же выбрасывался.
//
// Обрезка НИЖЕ при этом осталась и осталась намеренно — как последний рубеж. Если запрос
// однажды придёт с полными колонками (новый эндпоинт, забытый ENTRY_LIST_COLUMNS), ответ
// не станет молча десятимегабайтным: строка уже короткая — проверка длины бесплатна, строка
// длинная — она будет обрезана и честно помечена. Правило «в списке текста больше превью не
// бывает» держится независимо от того, кто собрал запрос.

/** Сколько символов content/summary оставить в СПИСОЧНОМ ответе.
 *  Хватает на заголовок (deriveEntryTitle берёт первую строку content) и на превью;
 *  полный текст экран детали до-загружает по id (GET /meetings/:id).
 *
 *  ⚠️ Продублировано в миграции 20260925090000 (`left(content, 400)`). Дрейф между кодом и
 *  базой ловит list-preview.db.test.ts — он сверяет живое превью с этой константой. */
export const LIST_PREVIEW_CHARS = 400;

type Row = {
  content?: string | null;
  summary?: string | null;
  /** Признак усечения из базы (generated-колонка). Из ответа убирается: наружу едет `truncated`. */
  list_truncated?: boolean | null;
  [k: string]: unknown;
};

function cut(s: string | null | undefined): { v: string | null; cut: boolean } {
  if (s == null) return { v: null, cut: false };
  if (s.length <= LIST_PREVIEW_CHARS) return { v: s, cut: false };
  return { v: s.slice(0, LIST_PREVIEW_CHARS), cut: true };
}

/**
 * Приводит строку к форме списочного ответа: превью текста и `truncated: true`, если в него
 * влезло не всё.
 *
 * Флаг — не косметика: по нему клиент понимает, что перед показом детали нужно до-загрузить
 * запись целиком, и не рисует обрезанный транскрипт как полный. Источник флага — база
 * (`list_truncated`, считается от ИСХОДНОЙ длины); обрезанная строка о себе такого сказать уже
 * не может, поэтому проверка по длине здесь — только дополнение, а не замена.
 *
 * Очередь вычитки (confirmed=false, единицы строк) через это не проходит — там текст нужен
 * сразу и целиком.
 */
export function toListRow<T extends Row>(
  row: T,
): Omit<T, "list_truncated"> & {
  content: string;
  summary: string | null;
  truncated?: true;
} {
  const { list_truncated: fromDb, ...rest } = row;
  const c = cut(rest.content as string | null | undefined);
  const s = cut(rest.summary as string | null | undefined);
  const out = { ...rest, content: c.v ?? "", summary: s.v };
  // База знает про усечение точно; длина — страховка на случай полных колонок в запросе.
  return (fromDb === true || c.cut || s.cut)
    ? { ...out, truncated: true as const }
    : out;
}

// ── GET /agent-meetings (списочный) ───────────────────────────────────────────

type AgentRow = {
  draft_notes_md?: string | null;
  /** Признак из базы (generated-колонка). Заменяет текст в выборке — см. issue #491. */
  has_draft_notes?: boolean | null;
  [k: string]: unknown;
};

/**
 * Оставляет в списочном ответе только признак наличия черновика тезисов.
 *
 * Зачем: `draft_notes_md` — это полные тезисы встречи, и в списке они не рендерятся; экран
 * ревью показывает название, дату и статус. Но список опрашивается каждые 10 секунд, поэтому
 * 154 кБ (18 черновиков на проде) превращались в ~55 МБ в час на одной открытой вкладке
 * (issue #108). Полный текст берёт деталь по GET /agent-meetings/:id — она и так его
 * до-загружает.
 *
 * С 25.09.2026 (issue #491) признак приходит из базы готовым (`has_draft_notes`), а колонка
 * с текстом в выборку не попадает вовсе: раньше она читалась, сериализовалась и тут же
 * выбрасывалась здесь — 119 мс базы на каждый опрос, из них ~88 мс на выброшенный текст.
 * Ветка по тексту осталась для вызовов, которые всё же принесли `draft_notes_md`.
 *
 * Признак нужен именно как поле, а не как «пришёл ли текст»: списку надо отличать «тезисы
 * готовятся» от «готовы», и без флага он бы читал отсутствие текста как «не готово» для ВСЕХ.
 * Пустая строка считается «не готово» — иначе список рапортует «готово» на пустышке.
 */
export function toAgentListRow<T extends AgentRow>(
  row: T,
): Omit<T, "draft_notes_md" | "has_draft_notes"> & { has_draft_notes: boolean } {
  const { draft_notes_md, has_draft_notes: fromDb, ...rest } = row;
  const flag = typeof fromDb === "boolean"
    ? fromDb
    : (draft_notes_md ?? "").trim().length > 0;
  return { ...rest, has_draft_notes: flag };
}
