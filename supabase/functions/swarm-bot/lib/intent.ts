// Классификация намерения пользователя по тексту сообщения.
// Чистые функции без внешних зависимостей — тестируются изолированно (intent_test.ts).

// Глаголы-команды «сделай что-то с УЖЕ существующей записью» (заменить/удалить/обновить/…).
// Сообщение вроде «замени эту форму на <url>» — это инструкция, а НЕ «сохрани ссылку».
// Без этого гейта index.ts молча сохранял такой текст как новую запись с командой в заголовке.
const EDIT_COMMAND_REGEX =
  /^\s*(?:замени(?:ть)?|поменя(?:й|ть)|измени(?:ть)?|обнови(?:ть)?|удали(?:ть)?|убери|убрать|сотри|стереть|отмени(?:ть)?|исправ(?:ь|ить)|поправ(?:ь|ить)|перенеси|перенести|переименуй|переименовать|отредактируй|редактируй)(?=\s|$)/iu;

/** true, если сообщение — команда изменить/удалить существующую запись, а не «сохрани это». */
export function isEditEntryCommand(text: string): boolean {
  return EDIT_COMMAND_REGEX.test(text);
}
