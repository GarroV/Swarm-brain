-- Общая встреча двух пространств (этап 2 решения docs/decisions/2026-11-05-second-workspace.md):
-- признак «ключ встречи подтверждён сервером» у черновика `meetings`.
--
-- `meetings.identity_key` уникален глобально, поэтому запись человека из другого пространства
-- находит строку по ключу. Ключ и состав встречи у рекордера присылает клиент — сами по себе они
-- участия не доказывают. `identity_verified = true` ставит только meeting-claim при создании
-- строки и только когда сервер сам нашёл календарный ключ в календаре создателя (служебный агент:
-- `resolveAgentScope` → `calendarKeys`). Встать в строку ДРУГОГО пространства можно, только если
-- строка подтверждена и ключ есть в календаре того, кто встаёт, — так же подтверждённый сервером.
--
-- Аддитивно: колонка с константным DEFAULT (без перезаписи таблицы). Старые строки — false
-- (не подтверждены): чужое пространство в них не встаёт.

alter table public.meetings
  add column if not exists identity_verified boolean not null default false;

comment on column public.meetings.identity_verified is
  'true — календарный ключ строки сервер сам нашёл в календаре её создателя (meeting-claim, '
  'resolveAgentScope). Только такая строка принимает запись из другого пространства. '
  'Ставит только сервер при создании строки; клиентскому признаку не верим.';
