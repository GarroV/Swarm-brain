-- Бэкфилл владельцев записей: у записи должен быть автор (issue #66).
--
-- Решение владельца 2026-08-22: «не должно быть ничьих — вся информация в базе принадлежит
-- кому-то». Код с 2026-08-22 больше не создаёт записи без владельца, но накопленные остались.
--
-- Проставляем ТОЛЬКО там, где автор виден в самих данных (поле added_by): 208 записей —
-- 134 встречи и 74 заметки. Остальные 59 (Granola, Read.ai, загрузки через Claude Desktop,
-- дайджест) остаются без владельца сознательно — решение владельца 2026-08-24: живого автора
-- там нет, и выдумывать его не надо.
--
-- owner_id — про АВТОРСТВО, а не про доступ. Видимость определяет is_private, и она здесь не
-- меняется: среди затронутых 208 записей приватных НЕТ ни одной (проверено до применения),
-- то есть ни одна запись никому не открывается и не закрывается.
--
-- Проверено на проде перед применением:
--   * напоминания о вычитке ходят по owner_id, но только для НЕвычитанных встреч старше 48ч —
--     под это не попадает ни одна из 208, спама не будет;
--   * записей, где на автора претендует больше одного человека, — 0;
--   * единственное изменение поведения: удаление записи через MCP разрешено только владельцу
--     (`swarm-mcp/index.ts`), а при пустом owner_id не мог никто. После бэкфилла автор сможет
--     удалить свою запись — это и есть смысл авторства.
--
-- Идемпотентно: WHERE owner_id IS NULL, повторный прогон не тронет ни строки.

-- 1-2. Автор известен из added_by (telegram_id или username).
UPDATE entries e
SET owner_id = u.telegram_id
FROM allowed_users u
WHERE e.owner_id IS NULL
  AND u.telegram_id IS NOT NULL
  AND (
    (e.added_by ~ '^[0-9]+$' AND u.telegram_id = e.added_by::bigint)
    OR lower(u.username) = lower(e.added_by)
  );
