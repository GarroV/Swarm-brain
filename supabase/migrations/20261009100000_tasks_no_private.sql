-- Задачи без «личных»: слой скрытости снимаем (решение владельца 09.10.2026).
-- Канон: docs/decisions/2026-10-09-tasks-no-private.md.
--
-- Владелец: «давай вот эту вот прослойку вообще уберем… мы просто не даем фильтровать для обычного
-- пользователя, кроме как его задач. У админа есть фильтр».
--
-- Шаг 1 из 2: данные. Код с этой ветки флаг больше не читает и не пишет; колонки tasks.is_private и
-- tasks.owner_id сносятся отдельной миграцией после раскатки кода (DROP COLUMN — только в два шага).
-- Флаг снимается здесь же, чтобы SQL-функции, которые ещё смотрят на него (перенос в спринте
-- accept_sprint_cycle, сброс демо), уже сейчас вели себя как без слоя.
--
-- Порядок важен: сперва то, что флаг защищал, переносится на явные признаки, потом флаг снимается.

-- 1. Публичная дорожная карта хаба прятала личные задачи. Чтобы снятие флага ничего не вынесло наружу,
--    личным задачам ставится явное «скрыта с хаба» (на проде 09.10 таких в публичных проектах — 3).
UPDATE public.tasks
   SET hidden_from_hub = true
 WHERE is_private = true
   AND hidden_from_hub IS DISTINCT FROM true;

-- 2. Личная задача без исполнителя после снятия флага стала бы «общей» и ушла бы в «Командные».
--    Исполнитель — её владелец (на проде 09.10 таких 2).
UPDATE public.tasks
   SET assignee_telegram_ids = ARRAY[owner_id]
 WHERE is_private = true
   AND owner_id IS NOT NULL
   AND cardinality(assignee_telegram_ids) = 0;

-- 3. Сам флаг. Значение по умолчанию у колонки и так false.
UPDATE public.tasks
   SET is_private = false
 WHERE is_private = true;

COMMENT ON COLUMN public.tasks.is_private IS
  'УСТАРЕЛО (09.10.2026): слой «личных задач» снят, код не читает и не пишет. Снос — второй шаг.';
