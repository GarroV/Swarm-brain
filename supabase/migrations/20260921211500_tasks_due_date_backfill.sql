-- Срок обязателен у каждой задачи (решение владельца 21.09.2026: «давай заложим
-- обязательное требование для задач на дедлайн. по дефолту дедлайн +1 день от времени
-- добавления»). Задача без срока не попадала ни в «Сегодня», ни в «Ближайшие» и жила
-- только в «Все» — то есть терялась так же, как замьюченная (issue #440).
--
-- Живым задачам без срока проставляем +7 дней от даты наката: «за эту неделю можно будет
-- настроить» (формулировка владельца). Не «завтра» — иначе 143 задачи разом падают в
-- «Сегодня» и превращают экран в стену.
--
-- Закрытые (done/cancelled) и архивные НЕ трогаем: они живут на оси времени по дате
-- закрытия, срок им не нужен, и подписывать закрытое задним числом — врать в журнале.
--
-- Журнал изменений (task_history) пишется кодом, а не триггером, поэтому массовая правка
-- в него не попадёт. Это осознанно: 143 строки «срок поставлен миграцией» — шум, а факт
-- разовой подписи записан здесь и в docs/decisions/2026-09-21-tasks-always-visible.md.
--
-- NOT NULL на колонку НЕ ставим этой миграцией: сначала код во всех точках создания
-- проставляет срок (сделано в том же PR — `_shared/tasks/due.ts`), и только следующим
-- шагом, убедившись на проде, что нулей больше не появляется, — констрейнт. Наше правило
-- двухшаговых миграций (CLAUDE.md, «Безопасность данных»).

update tasks
   set due_date = (current_date + interval '7 days')::date
 where due_date is null
   and archived_at is null
   and status not in ('done', 'cancelled');
