-- Выравнивание истории миграций после наката доски инициатив.
--
-- Почему файл существует. Миграцию 20260918120000 накатывали не через `supabase db push`
-- (у локального CLI отвалились права Management API), а через Management API напрямую — и он
-- проштамповал СВОИ версии-таймстампы: 20260918222844 и 20260918222907. Схема при этом ровно
-- та, что в файле, но записей о ней стало две, и обе чужие.
--
-- Это та самая мина, на которой проект стоял полтора месяца (#16, #101, #158): папка
-- `supabase/migrations/` и `supabase_migrations.schema_migrations` живут как две записи одной
-- истории, а `db push` начинает объявлять прод-версии потерянными. Поэтому лишние строки
-- сняты, а на их место поставлена версия файла.
--
-- Сама эта операция тоже попала в историю (версия 20260918223010) — и вот её файл, чтобы у
-- каждой прод-версии был файл, а у каждого файла прод-версия. Идемпотентна: повтор ничего не
-- ломает, потому что удалять уже нечего, а вставка гасится `on conflict`.
delete from supabase_migrations.schema_migrations
 where version in ('20260918222844', '20260918222907');

insert into supabase_migrations.schema_migrations (version, name)
values ('20260918120000', 'initiatives_board')
on conflict (version) do nothing;
