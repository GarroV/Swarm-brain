-- meetings.recorded_seconds — длительность записи, которой владеет текущий claim_owner (сек).
--
-- Зачем. Право транскрибации раздавалось ПЕРВОМУ заявившемуся, а claim подаётся в момент
-- ОСТАНОВКИ записи. Значит выигрывал тот, кто раньше нажал стоп, — то есть владелец САМОЙ
-- КОРОТКОЙ записи. Инцидент 17.08.2026 (встреча 251cd245-d6be-4abf-ba47-9755885eb05b):
-- коллега остановила запись на 3-й минуте при переходе в другой Google Meet и забрала право;
-- полная запись на 2ч26м пришла через 2.5 часа, получила decision=defer и была удалена с диска.
-- В базе остались 3 минуты организационной возни вместо всей встречи.
--
-- Теперь claim несёт длительность своей записи, сервер её хранит и отдаёт транскрибацию
-- ЗАМЕТНО более полной записи (перехват), а не тому, кто просто успел первым.
-- Для строк, заведённых старым клиентом (значение NULL), сервер оценивает длительность по
-- max(end) сегментов уже сохранённого транскрипта — см. meeting-claim.
--
-- ADD COLUMN — безопасно (см. CLAUDE.md §Миграции БД): существующие строки получают NULL,
-- старый клиент, не присылающий recorded_seconds, продолжает работать как раньше.

ALTER TABLE meetings ADD COLUMN IF NOT EXISTS recorded_seconds double precision;

COMMENT ON COLUMN meetings.recorded_seconds IS
  'Длительность записи текущего claim_owner в секундах. Основа арбитража: более полная запись перехватывает право транскрибации у более короткой. NULL — заведено клиентом без поддержки поля (оценивается по транскрипту).';
