-- Группы спринта (решение владельца 01.10.2026, docs/decisions/2026-10-01-sprint-drag-grouping.md):
-- в списке спринта задачу перетаскивают на задачу и называют группу — это запись в projects с
-- признаком sprint_group. Такая запись не видна на доске «Проекты», в селекторе проекта карточки
-- и в хабе, пока признак не сняли кнопкой «В проекты». Правило видимости — в коде
-- (_shared/tasks/sprint-groups.ts), колонка только хранит признак.
-- ADD COLUMN с дефолтом false — все существующие проекты остаются обычными.
alter table public.projects
  add column if not exists sprint_group boolean not null default false;

comment on column public.projects.sprint_group is
  'Группа спринта: создана перетаскиванием задачи на задачу в списке спринта. Скрыта с доски «Проекты», селекторов и хаба, пока не снята кнопкой «В проекты». Ставится только при создании.';
