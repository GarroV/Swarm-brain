-- Статус задачи — только из известного набора (issue #208, решение владельца 2026-09-05:
-- «пендинг вообще убираем, не понимаю смысла»).
--
-- Зачем ограничение, если код уже проверяет. Колонка `status` была свободной: `swarm-api`
-- писал `body.status` как есть, CHECK на неё никто не вешал. Так статус `pending` — которого
-- не знал ни один экран — лёг в 32 строки и полтора месяца прятал задачи от людей, на которых
-- они были назначены. Проверка в коде ловит только тот путь, который через неё проходит;
-- прямой SQL, новая функция или чужой скрипт — нет. CHECK ловит всех.
--
-- Данные под ограничение чистые (проверено на проде перед накатом 05.09.2026):
--   open 164 · done 75 · in_progress 22 · backlog 5 · pending 0 (удалены в тот же день).
-- `cancelled` строк не имеет, но код его пишет — в набор входит.
--
-- NULL разрешён намеренно: колонка nullable, дефолт проставляет код, и запрещать NULL —
-- отдельное решение с миграцией данных, а не побочный эффект этого.
--
-- Идемпотентно: повторный накат не упадёт.

alter table public.tasks drop constraint if exists tasks_status_check;

alter table public.tasks
  add constraint tasks_status_check
  check (status is null or status in ('open', 'in_progress', 'done', 'cancelled', 'backlog'));

comment on constraint tasks_status_check on public.tasks is
  'Набор статусов задачи. Заведён 05.09.2026 после #208: свободная колонка позволила статусу pending прятать 32 задачи полтора месяца. Единственный источник правды в коде — _shared/tasks/statuses.ts.';
