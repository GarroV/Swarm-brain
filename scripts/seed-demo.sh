#!/usr/bin/env bash
# Сброс демо-воркспейса к эталону: зовёт `public.demo_reset()` (scripts/seed-demo.sql). Тот же
# сброс сам идёт по расписанию pg_cron `demo-reset` каждые 30 минут — руками нужен после правки
# эталона или чтобы не ждать ближайшего тика.
#
# Главное здесь — не сид, а ЗАМОК. Скрипт, который льёт данные, рано или поздно запустят не
# в ту базу, и «демо» окажется в рабочем воркспейсе команды. Поэтому:
#   · по умолчанию целится в локальный контур;
#   · база не локальная → нужен явный `ALLOW_REMOTE=1`, иначе отказ;
#   · воркспейс — только `demo`: он зашит константой в самой функции, передать другой некуда.
set -euo pipefail
cd "$(dirname "$0")/.."

DB_URL="${DB_URL:-postgresql://postgres:postgres@127.0.0.1:54322/postgres}"

case "$DB_URL" in
  *127.0.0.1*|*localhost*) LOCAL=1 ;;
  *) LOCAL=0 ;;
esac

if [ "$LOCAL" -eq 0 ] && [ "${ALLOW_REMOTE:-0}" != "1" ]; then
  echo "отказ: база не локальная, а ALLOW_REMOTE=1 не задан." >&2
  echo "       заливка в живую базу — это раскатка: нужно «да» владельца и ночное окно." >&2
  exit 2
fi

echo "сброс демо → $([ "$LOCAL" -eq 1 ] && echo 'локальный контур' || echo 'УДАЛЁННАЯ база'), воркспейс 'demo'"
psql "$DB_URL" -v ON_ERROR_STOP=1 -At -f scripts/seed-demo.sql
