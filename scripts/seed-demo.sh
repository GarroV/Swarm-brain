#!/usr/bin/env bash
# Заливка демо-данных доски инициатив. Данные — в scripts/seed-demo.sql.
#
# Главное здесь — не сид, а ЗАМОК. Скрипт, который льёт данные, рано или поздно запустят не
# в ту базу, и «демо» окажется в рабочем воркспейсе команды. Поэтому:
#   · по умолчанию целится в локальный контур;
#   · база не локальная → нужен явный `ALLOW_REMOTE=1`, иначе отказ;
#   · воркспейс пишется только свой (`GROUP_ID`, по умолчанию `demo`) — рабочие слаги
#     отбиваются по списку, даже если ALLOW_REMOTE выставлен.
set -euo pipefail
cd "$(dirname "$0")/.."

DB_URL="${DB_URL:-postgresql://postgres:postgres@127.0.0.1:54322/postgres}"
GROUP_ID="${GROUP_ID:-demo}"

case "$DB_URL" in
  *127.0.0.1*|*localhost*) LOCAL=1 ;;
  *) LOCAL=0 ;;
esac

if [ "$LOCAL" -eq 0 ] && [ "${ALLOW_REMOTE:-0}" != "1" ]; then
  echo "отказ: база не локальная, а ALLOW_REMOTE=1 не задан." >&2
  echo "       заливка в живую базу — это раскатка: нужно «да» владельца и ночное окно." >&2
  exit 2
fi

# Рабочие воркспейсы демо-сидом не трогаем ни при каких флагах: демо-данные в рабочем
# пространстве видит вся команда и принимает за настоящие.
case "$GROUP_ID" in
  demo|demo-*) : ;;
  *) echo "отказ: GROUP_ID='$GROUP_ID' — сид пишет только в воркспейс demo/demo-*." >&2; exit 2 ;;
esac

echo "сид → $([ "$LOCAL" -eq 1 ] && echo 'локальный контур' || echo 'УДАЛЁННАЯ база'), воркспейс '$GROUP_ID'"
psql "$DB_URL" -v ON_ERROR_STOP=1 -v gid="$GROUP_ID" -f scripts/seed-demo.sql
