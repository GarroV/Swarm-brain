import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
import { validateCatalog } from "../src/lib/i18n/validation.mjs";
const require = createRequire(import.meta.url), ts = require("typescript");
const app = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

/** Strict JSON plus duplicate-property detection: JSON.parse alone silently accepts them. */
export function parseDictionary(text, filename) {
  const parsed = JSON.parse(text), tree = ts.parseJsonText(filename, text);
  if (tree.parseDiagnostics.length) throw new Error(`i18n: malformed JSON ${filename}`);
  const names = new Set();
  const root = tree.statements[0]?.expression;
  if (!root || !ts.isObjectLiteralExpression(root)) throw new Error(`i18n: flat dictionary required ${filename}`);
  for (const property of root.properties) {
    if (!ts.isPropertyAssignment(property) || !ts.isStringLiteral(property.name)) throw new Error(`i18n: string property required ${filename}`);
    if (names.has(property.name.text)) throw new Error(`i18n: duplicate key ${filename}:${property.name.text}`);
    names.add(property.name.text);
  }
  return parsed;
}

export function generateCatalog(root = app, check = false) {
  const directory = path.join(root, "src/lib/i18n/locales");
  const catalog = Object.fromEntries(fs.readdirSync(directory).filter((name) => name.endsWith(".json")).sort().map((name) => [
    name.slice(0, -5), parseDictionary(fs.readFileSync(path.join(directory, name), "utf8"), name),
  ]));
  validateCatalog(catalog);
  const output = "// Generated by scripts/i18n-catalog.mjs from locales/*.json. Do not edit.\n" +
    `export const dictionaries = ${JSON.stringify(catalog, null, 2)} as const;\n`;
  const target = path.join(root, "src/lib/i18n/catalog.generated.ts");
  if (check) {
    if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== output) throw new Error("i18n: stale catalog; npm run i18n:generate");
  } else fs.writeFileSync(target, output);
  return { languages: Object.keys(catalog), keys: Object.keys(catalog.en).length };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { console.log(JSON.stringify(generateCatalog(app, process.argv.includes("--check")))); }
  catch (error) { console.error(String(error)); process.exitCode = 1; }
}
