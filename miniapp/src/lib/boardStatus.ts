// Какие статусы на какой колонке доски проекта (SprintBoard). Колонки: «Бэклог задач»,
// «Открыто», «В работе», «Готово». Раньше бэклогом считалось всё, что не в трёх рабочих, и туда
// падали отменённые карточки (issue #1272). Отменённым на доске места нет — они видны в разделе
// «Задачи» по фильтру статуса.

/** Карточка живёт в колонке «Бэклог задач» — только статус backlog. */
export const isBacklogStatus = (s: string): boolean => s === "backlog";

/** Карточка в одной из трёх рабочих колонок. */
export const isWorkStatus = (s: string): boolean => s === "open" || s === "in_progress" || s === "done";

/** Показывается ли карточка на доске проекта вообще (отменённые — нет). */
export const isOnBoard = (s: string): boolean => isBacklogStatus(s) || isWorkStatus(s);
