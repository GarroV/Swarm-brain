export type SpacesKey = keyof typeof SPACES_TEXT;
export type Vars = Record<string, string | number>;


/** Строка по ключу и языку; `{имя}` заменяется значением из `vars`, неизвестное остаётся как есть. */
export function spacesText(lang: Lang, key: SpacesKey, vars?: Vars): string {
  const raw = SPACES_TEXT[key][lang];
  return vars ? raw.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m)) : raw;
}
