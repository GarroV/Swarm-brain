"use client";
import { SearchBtn } from "./ui";
import { useRoyNav } from "./nav";

// Правый угол шапки мобильных корневых экранов: ПОИСК.
//
// Колокольчика здесь больше нет (issue #247). Он был и тут, и в `RoyHeader` (ui.tsx),
// который рисует свой на мобайле, — а экраны кладут `HeaderActions` в тот же `right`.
// В итоге на всех корневых экранах стояли ДВА одинаковых колокольчика с одним бейджем.
// Две правки одного угла (22.08 и 24.08) не увидели друг друга. Дом у колокольчика один —
// `RoyHeader`: он часть оболочки, а не экрана, и знает про десктоп, где колокольчик уже
// стоит в полосе «← Главная».
// Оба контрола раньше жили в шапке «Поиска» — единственного экрана, который был домом. После
// редизайна навигации (2026-08-22) дом — «Задачи», а «Поиск» стал push-экраном, поэтому оба
// уехали бы вглубь: уведомления надо видеть с любого таба, искать — тоже.
export function HeaderActions() {
  const { push } = useRoyNav();
  return (
    <div className="flex items-center gap-1.5">
      <SearchBtn onClick={() => push({ view: "ask" })} />
    </div>
  );
}
